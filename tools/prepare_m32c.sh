#!/bin/sh
# prepare_m32c.sh -- the RC8650's CPU, once per checkout: GDB 14.2's m32c simulator, patched by librc8650, with its
# two instruction decoders generated.  Run on the build machine (also before a cross build: the decoder generator
# runs here).  Writes third_party/m32c/ (or $1).
#
#   tools/prepare_m32c.sh [OUTDIR]          RC8650_DIR=... if librc8650 is not in third_party/librc8650
#
# GDB is GPL-3, as librc8650 and this emulator are; only sim/m32c is taken from it.
set -e
cd "$(dirname "$0")/.."
OUT=${1:-third_party/m32c}
RC=${RC8650_DIR:-third_party/librc8650}
GDB=gdb-14.2
SHA=2d4dd8061d8ded12b6c63f55e45344881e8226105f4d2a9b234040efa5ce7772
URL=https://ftp.gnu.org/gnu/gdb/$GDB.tar.xz
CACHE=third_party/cache

RC=$(cd "$RC" 2>/dev/null && pwd) || { echo "no librc8650 at ${RC8650_DIR:-third_party/librc8650}" >&2; exit 1; }
[ -f "$RC/sim/rc865x-sim.patch" ] || { echo "no librc8650 at $RC (git submodule update --init, or set RC8650_DIR)" >&2; exit 1; }
mkdir -p "$CACHE"
if [ ! -f "$CACHE/$GDB.tar.xz" ]; then
    echo "fetching $URL"
    curl -fL -o "$CACHE/$GDB.tar.xz.part" "$URL"
    mv "$CACHE/$GDB.tar.xz.part" "$CACHE/$GDB.tar.xz"
fi
got=$( (shasum -a 256 "$CACHE/$GDB.tar.xz" 2>/dev/null || sha256sum "$CACHE/$GDB.tar.xz") | cut -d' ' -f1)
[ "$got" = "$SHA" ] || { echo "$CACHE/$GDB.tar.xz: unexpected sha256 $got" >&2; exit 1; }

TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
# busybox's tar (w64devkit's, on Windows) extracts the folder and still ends "not found in archive": the files decide
tar -xJf "$CACHE/$GDB.tar.xz" -C "$TMP" "$GDB/sim/m32c" || [ -f "$TMP/$GDB/sim/m32c/opc2c.c" ]
# quiet by its output thrown away, not by -s, which busybox's patch does not have
(cd "$TMP/$GDB" && patch -p1 < "$RC/sim/rc865x-sim.patch" > /dev/null)

rm -rf "$OUT"
mkdir -p "$OUT/gen"
cp "$TMP/$GDB/sim/m32c/"*.c "$TMP/$GDB/sim/m32c/"*.h "$TMP/$GDB/sim/m32c/"*.opc "$OUT/"
# the decoders, generated by the simulator's own opc2c (built for this machine)
# host_getline.h: getline where the build machine's C library has none (Windows); nothing elsewhere
${HOSTCC:-cc} -O2 -w -I"$RC" -include tools/host_getline.h -o "$TMP/opc2c" "$OUT/opc2c.c"
for d in r8c m32c; do
    "$TMP/opc2c" -l "$TMP/$d.log" "$OUT/$d.opc" > "$OUT/gen/$d.c"
done
# what the patch was taken from, for the build to tell a stale tree
(cd "$RC" && git rev-parse HEAD 2>/dev/null || echo unknown) > "$OUT/LIBRC8650_REV"
shasum -a 256 "$RC/sim/rc865x-sim.patch" 2>/dev/null | cut -d' ' -f1 >> "$OUT/LIBRC8650_REV" || true
echo "m32c simulator ready in $OUT"
